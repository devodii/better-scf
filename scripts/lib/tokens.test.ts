import { describe, expect, it } from 'vitest';
import { formatTokensScss, mergeTokenValues, missingTokens, normalizeColor } from './tokens';

describe('normalizeColor', () => {
  it('converts opaque rgb to hex', () => {
    expect(normalizeColor('rgb(11, 11, 14)')).toBe('#0b0b0e');
    expect(normalizeColor('rgb(255 255 255)')).toBe('#ffffff');
  });

  it('keeps partial alpha and drops full transparency', () => {
    expect(normalizeColor('rgba(0, 0, 0, 0.5)')).toBe('rgba(0, 0, 0, 0.5)');
    expect(normalizeColor('rgb(0 0 0 / 50%)')).toBe('rgba(0, 0, 0, 0.5)');
    expect(normalizeColor('rgba(0, 0, 0, 0)')).toBeNull();
    expect(normalizeColor('transparent')).toBeNull();
  });

  it('passes other color spaces through', () => {
    expect(normalizeColor('oklch(0.5 0.1 200)')).toBe('oklch(0.5 0.1 200)');
  });
});

describe('mergeTokenValues', () => {
  it('takes the first value found, in page order', () => {
    expect(mergeTokenValues([{ bg: '#111111' }, { bg: '#222222', link: '#3333ff' }])).toEqual({
      bg: '#111111',
      link: '#3333ff',
    });
  });
});

describe('formatTokensScss', () => {
  const values = {
    bg: '#0b0b0e',
    surface: '#1c1b22',
    'chip-purple-bg': '#4b3a8f',
    'accent-yellow': '#ffd600',
    'font-body': '"Inter", sans-serif',
  };
  const scss = formatTokensScss(values, { '--radius': '8px', '--bad name': 'x' });

  it('writes the variables, derived tokens and the :host block', () => {
    expect(scss).toMatch(/^\/\/ GENERATED by scripts\/scrape-tokens\.ts\. Do not edit by hand\./);
    expect(scss).toContain('$bscf-bg: #0b0b0e; // body background');
    expect(scss).toContain('$bscf-font-body: "Inter", sans-serif;');
    expect(scss).toContain('$track-integration: $bscf-chip-purple-bg;');
    expect(scss).toContain('$track-rfp: $bscf-accent-yellow;');
    expect(scss).toContain('$muted-chip: color.mix(#fff, $bscf-surface, 6%);');
    expect(scss).toContain(':host {');
    expect(scss).toContain('  --bscf-bg: #{$bscf-bg};');
    expect(scss).toContain('  --bscf-muted-chip: #{$muted-chip};');
    expect(scss).toContain('  --bscf-site-radius: 8px;');
  });

  it('omits tokens that were not found and says so, without inventing values', () => {
    expect(scss).not.toContain('$bscf-link');
    expect(scss).not.toContain('$track-open');
    expect(scss).toMatch(/NOT FOUND on the site, omitted: .*link/);
    expect(missingTokens(values)).toContain('link');
    expect(scss).not.toContain('bad name');
  });

  it('cannot be broken out of by a value from the page', () => {
    const out = formatTokensScss({ 'font-body': 'x; } body { color: red' });
    const declaration = out.split('\n').find((line) => line.startsWith('$bscf-font-body:')) ?? '';
    expect(declaration).not.toMatch(/[{}]/);
    expect(declaration.match(/;/g)).toHaveLength(1);
  });

  it('cannot comment out the rest of a line with // or /*', () => {
    const out = formatTokensScss(
      { 'font-body': 'Inter // hide', bg: 'red /* open' },
      { '--x': 'a //b', '--y': 'c /*d' },
    );
    const lines = out.split('\n');
    const body = lines.find((line) => line.startsWith('$bscf-font-body:')) ?? '';
    const bg = lines.find((line) => line.startsWith('$bscf-bg:')) ?? '';
    expect(body.slice(0, body.indexOf(';'))).not.toContain('//');
    expect(bg.slice(0, bg.indexOf(';'))).not.toContain('/*');
    expect(out).not.toContain('/*');
    expect(lines.find((line) => line.includes('--bscf-site-x:'))).not.toContain('//');
    expect(lines.find((line) => line.includes('--bscf-site-y:'))).not.toContain('/*');
  });
});
